def _load_classic_indices() -> tuple[dict[str, dict[str, str]], dict[str, dict[str, str]]]:
    f1 = json.loads((DATA_DIR / "formulas.json").read_text(encoding="utf-8"))
    f2 = json.loads((DATA_DIR / "jinkui_formulas.json").read_text(encoding="utf-8"))
    ac = json.loads((DATA_DIR / "acupuncture" / "acupoints.json").read_text(encoding="utf-8"))
    f_map: dict[str, dict[str, str]] = {}
    for x in (f1 if isinstance(f1, list) else f1.get("formulas", [])) + (f2 if isinstance(f2, list) else f2.get("formulas", [])):
        f_map[x["name"]] = {"id": x["id"], "name": x["name"]}
    for alias, target in {
        "旋覆代赭汤": "旋覆代赭石汤",
        "桂枝去芍药加麻辛附子汤": "桂甘姜枣麻辛附子汤",
        "小健中汤": "小建中汤",
        "瓜蒌薤白白酒汤": "栝蒌薤白白酒汤",
    }.items():
        if target in f_map:
            f_map.setdefault(alias, f_map[target])
    pt_map: dict[str, dict[str, str]] = {}
    pts_list = ac if isinstance(ac, list) else (ac.get("items") or ac.get("acupoints") or [])
    for x in pts_list:
        nm = x.get("canonical_name") or x.get("name") or x["id"].split(":")[-1]
        entry = {"id": x["id"], "name": nm}
        pt_map[nm] = entry
        for al in x.get("aliases") or []:
            pt_map.setdefault(al, entry)
    return f_map, pt_map


def _extract_ht_pdf_pages() -> dict[int, dict[str, Any]]:
    pages = [
        json.loads(ln)
        for ln in (LIB_DIR / "ni-hantang-formulas-pdf.jsonl").read_text(encoding="utf-8").splitlines()
        if ln.strip()
    ]
    events: list[tuple[int, int, int, str]] = []
    for pg in pages:
        pno = int(pg["page_no"])
        if pno <= 2:
            continue
        txt = pg.get("body_text") or ""
        seen_here: set[int] = set()
        for m in re.finditer(r"(?m)^\s*(HT-(\d{1,3})\b[^\n]{0,60})", txt):
            num = int(m.group(2))
            if 1 <= num <= 100 and num not in seen_here:
                events.append((num, pno, m.start(), m.group(1).strip()))
                seen_here.add(num)
        for m in re.finditer(r"(HT-(\d{1,3})\s+[\u4e00-\u9fff][^\n]{0,50})", txt):
            num = int(m.group(2))
            if 1 <= num <= 100 and num not in seen_here:
                events.append((num, pno, m.start(), m.group(1).strip()))
                seen_here.add(num)
    first_ev: dict[int, tuple[int, int, str]] = {}
    for num, pno, pos, title in sorted(events, key=lambda x: (x[1], x[2])):
        if num not in first_ev:
            first_ev[num] = (pno, pos, title)
    ordered = sorted(first_ev.items(), key=lambda kv: (kv[1][0], kv[1][1]))
    out: dict[int, dict[str, Any]] = {}
    for idx, (num, (pno, _, title)) in enumerate(ordered):
        next_pno = ordered[idx + 1][1][0] if idx + 1 < len(ordered) else len(pages)
        out[num] = {
            "page_no": pno,
            "end_page": next_pno,
            "title_raw": title,
            "q": f"HT-{num}",
        }
    return out


def build_catalog() -> dict[str, Any]:
    f_map, pt_map = _load_classic_indices()
    pdf_pages = _extract_ht_pdf_pages()

    num_to_cat: dict[int, dict[str, Any]] = {}
    for c in CATEGORIES:
        for n in c["nums"]:
            num_to_cat[n] = c

    formulas: list[dict[str, Any]] = []
    for sp in FORMULA_SPECS:
        num = sp["num"]
        cat = num_to_cat[num]
        pg_info = pdf_pages[num]
        linked_classics = []
        for cname in sp.get("classics", []):
            hit = f_map.get(cname)
            if not hit:
                # Fuzzy prefix check
                for fn, fv in f_map.items():
                    if cname in fn:
                        hit = fv
                        break
            if hit:
                linked_classics.append(hit)
        linked_pts = []
        for pname in sp.get("points", []):
            hit = pt_map.get(pname)
            if hit:
                linked_pts.append(hit)

        formulas.append(
            {
                "id": f"hantang:ht-{num:02d}",
                "num": num,
                "ht_number": f"HT-{num}",
                "name": sp["name"],
                "full_title": f"HT-{num} {sp['name']}",
                "category_id": cat["id"],
                "category": cat["title"],
                "category_short": cat["short"],
                "safety_level": sp["safety"],
                "ni_original": {
                    "indications": sp["ind"],
                    "pathogenesis": sp["path"],
                    "partial_herbs": sp["herbs"],
                    "is_partial_disclosure": bool(sp["partial"]),
                    "dosage_method": sp["dose"],
                    "contraindications": sp["contra"],
                },
                "ziji_note": {
                    "commentary": sp["ziji"],
                    "linked_classical_formulas": linked_classics,
                    "linked_acupoints": linked_pts,
                },
                "clinical_tags": sp.get("tags", []),
                "source_anchor": {
                    "book_id": "ni-hantang-formulas-pdf",
                    "book_title": "倪海夏-汉唐中医方剂讲解",
                    "page_no": pg_info["page_no"],
                    "end_page": pg_info["end_page"],
                    "q": f"HT-{num} {sp['name'].split('（')[0]}",
                },
            }
        )

    formulas.sort(key=lambda x: x["num"])

    # Enrich linked entity IDs in western_history_rules & cases_index
    ht_by_num = {f["num"]: f for f in formulas}
    for wr in WESTERN_HISTORY_RULES:
        wr["linked_classical_items"] = [f_map[n] for n in wr.get("linked_classics", []) if n in f_map]
    for cs in CASES_INDEX:
        cs["linked_formula_items"] = [f_map[n] for n in cs.get("formulas", []) if n in f_map]
        cs["linked_acupoint_items"] = [pt_map[n] for n in cs.get("points", []) if n in pt_map]
    for rl in CLINICAL_REDLINES_HT:
        m = re.search(r"HT-(\d+)", rl.get("ref", ""))
        if m:
            fobj = ht_by_num.get(int(m.group(1)))
            if fobj:
                rl["anchor"] = dict(fobj["source_anchor"])
    for d in DU_SPINE_DIAGNOSTICS:
        pt = pt_map.get(d["acupoint"])
        if pt:
            d["acupoint_id"] = pt["id"]

    return {
        "version": "hantang-milestone1-v1",
        "formula_count": len(formulas),
        "missing_numbers": MISSING_HT_NUMBERS,
        "source_books": [
            {"book_id": "ni-hantang-formulas-pdf", "title": "《倪海夏-汉唐中医方剂讲解》"},
            {"book_id": "ni-hantang-articles-cases-pdf", "title": "《倪海厦汉唐中医经典文章医案集》"},
            {"book_id": "ni-hantang-clinic-notes-pdf", "title": "《倪海厦传统中医跟诊过程》"},
        ],
        "epistemic_notice": "⚠️ 原书《汉唐百方》多数方剂仅公开部分核心药味（附……等），旨在阐明病机与取象立法；研习时严禁把局部示例当作完整成方直接抄方套用。且严正区隔「倪海厦原论」「紫极讲者按语」与「临床一线跟诊实录」。",
        "categories": [{"id": c["id"], "title": c["title"], "short": c["short"], "count": len(c["nums"])} for c in CATEGORIES],
        "formulas": formulas,
        "du_spine_diagnostics": DU_SPINE_DIAGNOSTICS,
        "special_palpation_points": SPECIAL_PALPATION_POINTS,
        "western_history_rules": WESTERN_HISTORY_RULES,
        "prognosis_and_recovery_criteria": PROGNOSIS_CRITERIA,
        "clinical_redlines": CLINICAL_REDLINES_HT,
        "cases_index": CASES_INDEX,
    }


def main() -> None:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    payload = build_catalog()
    OUT_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({payload['formula_count']} HT formulas, {len(payload['cases_index'])} cases)")


if __name__ == "__main__":
    main()
